import fs from "node:fs";
import assert from "node:assert/strict";
import ts from "typescript";
const exports = {};
new Function("exports", ts.transpileModule(fs.readFileSync("app/lib/auth/validation.ts", "utf8"), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText)(exports);
const { normalizeMobile, validateAuth, parseAuthFields, blankAuthFields } = exports;
const valid = { ...blankAuthFields, fullName: "Test Buyer", mobile: "+91 98765 43210", email: "buyer@example.test", password: "Test passphrase 2026!", confirmPassword: "Test passphrase 2026!", accountType: "Buyer" };
assert.deepEqual(validateAuth(valid, "signup"), {});
assert.equal(normalizeMobile(valid.mobile), "+919876543210");
assert.equal(normalizeMobile("1234567890"), null);
assert.equal(normalizeMobile("+449876543210"), null);
for (const field of ["fullName", "mobile", "email", "password", "confirmPassword", "accountType"]) assert.ok(validateAuth({ ...valid, [field]: "" }, "signup")[field]);
assert.ok(validateAuth({ ...valid, accountType: "Administrator" }, "signup").accountType);
assert.ok(validateAuth({ ...valid, password: "short" }, "signup").password);
assert.ok(validateAuth({ ...valid, password: "x".repeat(129) }, "reset").password);
assert.deepEqual(validateAuth({ ...valid, password: "legacy-pass" }, "login"), {});
assert.equal(parseAuthFields({ remember: "true", email: 123 }).remember, false);
assert.equal(parseAuthFields(null).email, "");
console.log("Passed authentication validation, Indian mobile normalization, password rules, account-type allowlist and safe input parsing.");
